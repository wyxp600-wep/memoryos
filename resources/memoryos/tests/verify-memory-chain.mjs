import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {openDb,writeMemory,readMemory,updateMemory} from '../dist/db.js';
import {memoryFields} from '../dist/memory-fields.js';
import {metadataForMemory,metadataCandidates} from '../dist/memory-metadata.js';
import {parseTaskRows} from '../dist/task-domain.js';
import {buildApp} from '../dist/dashboard.js';
process.env.EMBED_MODE='fake';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'memory-chain-'));
process.env.MEMORY_DB=path.join(root,'memory.db');
process.env.MEMORYOS_DATA_DIR=root;
const db=openDb(process.env.MEMORY_DB);
const raw='  ## 结论\n保留 **加粗** 与空行。\n\n```js\n状态：不是字段\nconst x = "#123";\n```\n\n## 关键词\nAlphaEngine；ERR_ZQ91；正文完整\n\n## 适用范围\nWindows\n\n## 依据\n原文证据\n\n## 行动\n检查后执行\n\n## 状态\n待验证，最后核验日期：2026-11-16。\n ';
const row=writeMemory(db,{content:raw,type:'experience',agent:'human:test',agent_fpath:null,project:'fixture',source:'human'});
assert.equal(readMemory(db,row.id).content,raw);
assert.equal(memoryFields(raw).length,6);
assert.ok(memoryFields(raw)[0].value.includes('状态：不是字段'));
const meta=metadataForMemory(db,row.id);
assert.ok(meta.keywords.some(t=>t.term==='ERR_ZQ91'));
assert.ok(meta.tags.length>0);
assert.ok(metadataCandidates(db,['ERR_ZQ91'],'fixture').some(t=>t.id===row.id));
updateMemory(db,row.id,{content:raw.replaceAll('ERR_ZQ91','ERR_NEW92')});
assert.ok(!metadataCandidates(db,['ERR_ZQ91'],'fixture').some(t=>t.id===row.id));
assert.ok(metadataCandidates(db,['ERR_NEW92'],'fixture').some(t=>t.id===row.id));
const task=writeMemory(db,{content:'[task][assignee:?][status:pending] 显示校验\n\n完整任务 '+ '正文'.repeat(200)+'\n示例 [assignee:别人] [scope:例子]',type:'task',agent:'human:test',agent_fpath:null,project:'fixture',source:'human'});
const parsed=parseTaskRows(db,{limit:100}).find(t=>t.id===task.id);
assert.ok(parsed.body.length>400);
assert.ok(parsed.body.includes('[assignee:别人]'));
assert.equal(parsed.assignee,'?');
const app=buildApp(db,{token:'fixture-only'});await app.ready();
const detail=await app.inject({method:'GET',url:'/api/memory/'+row.id,headers:{authorization:'Bearer fixture-only'}});
assert.equal(detail.statusCode,200);assert.equal(detail.json().content,raw.replaceAll('ERR_ZQ91','ERR_NEW92'));
const found=await app.inject({method:'GET',url:'/api/memory/search?query=ERR_NEW92&project=fixture',headers:{authorization:'Bearer fixture-only'}});
assert.equal(found.statusCode,200);assert.ok(found.json().rows.some(r=>r.id===row.id));
const unauth=await app.inject({method:'GET',url:'/api/memory/'+row.id});assert.equal(unauth.statusCode,401);
for(let i=0;i<6;i++)writeMemory(db,{content:'ERR_NEW92 相关活跃记录 '+i,type:'experience',agent:'human:test',agent_fpath:null,project:'fixture',source:'human'});
const cold=writeMemory(db,{content:'ERR_NEW92 相关归档记录',type:'experience',agent:'human:test',agent_fpath:null,project:'fixture',source:'human',status:'archived'});
const mixed=await app.inject({method:'GET',url:'/api/memory/search?query=ERR_NEW92&project=fixture&limit=3',headers:{authorization:'Bearer fixture-only'}});
assert.equal(mixed.statusCode,200);assert.equal(mixed.json().rows.length,3);assert.ok(mixed.json().rows.some(r=>r.id===cold.id));
const onlyCold=await app.inject({method:'GET',url:'/api/memory/search?query=ERR_NEW92&project=fixture&status=archived&limit=3',headers:{authorization:'Bearer fixture-only'}});
assert.equal(onlyCold.statusCode,200);assert.ok(onlyCold.json().rows.every(r=>r.status==='archived'));
console.log('PASS 原文往返、围栏字段、自动词标签、更新失效、完整任务正文、正文控制标签、HTTP读取搜索与鉴权');
if(process.argv.includes('--serve')){await app.listen({host:'127.0.0.1',port:18896});console.log('ISOLATED_UI http://127.0.0.1:18896/?token=fixture-only');}
else{await app.close();db.close();}
